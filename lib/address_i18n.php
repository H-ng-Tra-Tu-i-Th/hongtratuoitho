function addr_t(string $key, array $vars = []): string
{
    $lang = function_exists('current_lang') ? current_lang() : 'vi';
    $dict = address_i18n_dictionary();
    $text = $dict[$lang][$key] ?? $dict['vi'][$key] ?? $key;
    foreach ($vars as $name => $value) $text = str_replace('{' . $name . '}', (string)$value, $text);
    return $text;
}

/** Strings read by assets/js/google-location.js through window.__HUIYI_I18N__.address. */
function address_render_js_i18n(): string
{
    $lang = function_exists('current_lang') ? current_lang() : 'vi';
    $dict = address_i18n_dictionary();
    $payload = ['lang' => $lang, 'address' => $dict[$lang] ?? $dict['vi']];
    return '<script>window.__HUIYI_I18N__ = Object.assign(window.__HUIYI_I18N__ || {}, ' . json_encode($payload, JSON_UNESCAPED_UNICODE | JSON_HEX_TAG | JSON_HEX_AMP) . ');</script>' . "\n";
}
