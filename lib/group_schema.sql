CREATE TABLE IF NOT EXISTS group_rooms (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 public_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 invite_token CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL UNIQUE,
 owner_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 create_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 title VARCHAR(160) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'open',
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 checkout_mode VARCHAR(16) NOT NULL DEFAULT 'together',
 payment_protocol_version TINYINT UNSIGNED NOT NULL DEFAULT 2,
 settlement_json LONGTEXT NULL,
 coupon_code VARCHAR(80) NOT NULL DEFAULT '',
 coupon_type VARCHAR(30) NOT NULL DEFAULT '',
 coupon_source VARCHAR(20) NOT NULL DEFAULT '',
 coupon_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 lock_signature CHAR(64) NULL,
 order_id BIGINT UNSIGNED NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at DATETIME NOT NULL,
 payment_expires_at DATETIME NULL,
 submitted_at DATETIME NULL,
 UNIQUE KEY uq_group_create(owner_hash,create_key),
 KEY idx_group_owner(owner_hash,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS group_members (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 room_id BIGINT UNSIGNED NOT NULL,
 device_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 nickname VARCHAR(80) NOT NULL,
 ready TINYINT NOT NULL DEFAULT 0,
 payment_method VARCHAR(20) NOT NULL DEFAULT 'bank_transfer',
 payment_status VARCHAR(16) NOT NULL DEFAULT 'pending',
 payment_completed_at DATETIME NULL,
 payment_requested_at DATETIME NULL,
 payment_requested_amount DECIMAL(12,2) NULL,
 payment_confirmed_at DATETIME NULL,
 payment_confirmed_by_member_id BIGINT UNSIGNED NULL,
 payment_confirmed_amount DECIMAL(12,2) NULL,
 payment_received_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 payment_refunded_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 payment_invalidated_at DATETIME NULL,
 payment_invalidation_reason VARCHAR(32) NOT NULL DEFAULT '',
 joined_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_group_member(room_id,device_hash),
 UNIQUE KEY uq_group_nickname(room_id,nickname),
 KEY idx_group_device(device_hash),
 CONSTRAINT fk_group_member_room FOREIGN KEY(room_id) REFERENCES group_rooms(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS group_removed_members (
 room_id BIGINT UNSIGNED NOT NULL,
 device_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 original_member_id BIGINT UNSIGNED NOT NULL,
 removed_by_member_id BIGINT UNSIGNED NOT NULL,
 removed_at DATETIME NOT NULL,
 PRIMARY KEY(room_id,device_hash),
 CONSTRAINT fk_group_removed_room FOREIGN KEY(room_id) REFERENCES group_rooms(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS group_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 room_id BIGINT UNSIGNED NOT NULL,
 member_id BIGINT UNSIGNED NOT NULL,
 request_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 selection_json LONGTEXT NOT NULL,
 snapshot_json LONGTEXT NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_group_item_request(member_id,request_key),
 KEY idx_group_item_room(room_id,member_id),
 CONSTRAINT fk_group_item_room FOREIGN KEY(room_id) REFERENCES group_rooms(id) ON DELETE CASCADE,
 CONSTRAINT fk_group_item_member FOREIGN KEY(member_id) REFERENCES group_members(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS group_payment_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 room_id BIGINT UNSIGNED NOT NULL,
 member_id BIGINT UNSIGNED NULL,
 actor_member_id BIGINT UNSIGNED NULL,
 event_type VARCHAR(32) NOT NULL,
 amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 reason VARCHAR(240) NOT NULL DEFAULT '',
 reference VARCHAR(80) NOT NULL,
 member_name VARCHAR(80) NOT NULL DEFAULT '',
 quote_signature CHAR(64) NULL,
 room_revision BIGINT UNSIGNED NOT NULL,
 snapshot_json LONGTEXT NOT NULL,
 seed_key VARCHAR(80) NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_group_payment_room(room_id,id),
 KEY idx_group_payment_member(room_id,member_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
